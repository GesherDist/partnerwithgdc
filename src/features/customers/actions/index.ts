/**
 * Update an existing customer from form data
 */
export async function updateCustomer(
  id: string,
  formData: FormData
): Promise<ActionResult<Customer>> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();

  if (!user) {
    return { success: false, error: 'Authentication required' };
  }

  // Get app user ID (public.users.id) from auth user ID
  const appUser = await getAppUserByAuthId(user.id);
  if (!appUser) {
    return { success: false, error: 'User profile not found' };
  }

  // Parse form data - only include provided fields
  const rawData: Record<string, unknown> = {};

  const stringFields = [
    'customerCode', 'name', 'legalName', 'channel',
    'address1', 'address2', 'city', 'state', 'zip', 'country',
    'shippingAddress1', 'shippingAddress2', 'shippingCity', 'shippingState', 'shippingZip', 'shippingCountry',
    'phone', 'email', 'website',
    'taxId', 'taxExemptNumber',
    'creditStatus', 'creditTerms',
    'preferredLocationId', 'defaultPaymentMethod', 'status', 'internalNotes'
  ];

  for (const field of stringFields) {
    const value = formData.get(field);
    if (value !== null) {
      rawData[field] = value === '' ? null : value;
    }
  }

  // Handle boolean fields
  if (formData.has('useSeparateShipping')) {
    rawData.useSeparateShipping = formData.get('useSeparateShipping') === 'true';
  }
  if (formData.has('taxExempt')) {
    rawData.taxExempt = formData.get('taxExempt') === 'true';
  }

  // Handle credit limit (convert to cents)
  if (formData.has('creditLimit')) {
    const creditLimitStr = formData.get('creditLimit') as string;
    rawData.creditLimit = Math.round(parseFloat(creditLimitStr || '0') * 100);
  }

  // Handle open balance (convert to cents)
  if (formData.has('openBalance')) {
    const openBalanceStr = formData.get('openBalance') as string;
    rawData.openBalance = Math.round(parseFloat(openBalanceStr || '0') * 100);
  }

  // Uppercase customer code if provided
  if (rawData.customerCode) {
    rawData.customerCode = (rawData.customerCode as string).toUpperCase();
  }

  // Validate
  const validation = updateCustomerSchema.safeParse(rawData);
  if (!validation.success) {
    return {
      success: false,
      error: 'Validation failed',
      errors: validation.error.flatten().fieldErrors as Record<string, string[]>,
    };
  }

  const result = await customerService.update(id, validation.data, appUser.id);

  if (result.success) {
    revalidatePath('/customers');
    revalidatePath(`/customers/${id}`);
    revalidatePath('/api/customers');
  }

  return result;
}

/**
 * Update customer from JSON data
 */
export async function updateCustomerFromData(
  id: string,
  data: unknown
): Promise<ActionResult<Customer>> {
  try {
    const supabase = await createClient();
    const { data: { user } } = await supabase.auth.getUser();

    if (!user) {
      return { success: false, error: 'Authentication required' };
    }

    // Get app user ID (public.users.id) from auth user ID
    const appUser = await getAppUserByAuthId(user.id);
    if (!appUser) {
      return { success: false, error: 'User profile not found' };
    }

    // If data is form values, convert to DTO format
    const dataObj = data as Record<string, unknown>;
    const convertedData = typeof data === 'object' && data !== null
      ? {
          ...data,
          creditLimit: 'creditLimit' in dataObj && typeof dataObj.creditLimit === 'string'
            ? Math.round(parseFloat(dataObj.creditLimit as string || '0') * 100)
            : dataObj.creditLimit,
          openBalance: 'openBalance' in dataObj && typeof dataObj.openBalance === 'string'
            ? Math.round(parseFloat(dataObj.openBalance as string || '0') * 100)
            : dataObj.openBalance,
        }
      : data;

    // Validate
    const validation = updateCustomerSchema.safeParse(convertedData);
    if (!validation.success) {
      return {
        success: false,
        error: 'Validation failed',
        errors: validation.error.flatten().fieldErrors as Record<string, string[]>,
      };
    }

    const result = await customerService.update(id, validation.data, appUser.id);

    if (result.success) {
      revalidatePath('/customers');
      revalidatePath(`/customers/${id}`);
      revalidatePath('/api/customers');
    }

    return result;
  } catch (error) {
    console.error('updateCustomerFromData unexpected error:', error);
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Failed to update customer',
    };
  }
}

