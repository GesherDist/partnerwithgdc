/**
 * Create a new customer from form data
 */
export async function createCustomer(formData: FormData): Promise<ActionResult<Customer>> {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();

  if (!user) {
    return { success: false, error: 'Authentication required' };
  }

  // Get app user ID (public.users.id) from auth user ID
  const appUser = await getAppUserByAuthId(user.id);
  if (!appUser) {
    return { success: false, error: 'User profile not found' };
  }

  // Parse form data (customerCode is auto-generated by service)
  const rawData = {
    customerCode: '', // Auto-generated
    name: formData.get('name') as string,
    legalName: formData.get('legalName') as string || '',
    channel: formData.get('channel') as string || 'dealer',

    // Billing Address
    address1: formData.get('address1') as string || '',
    address2: formData.get('address2') as string || '',
    city: formData.get('city') as string || '',
    state: formData.get('state') as string || '',
    zip: formData.get('zip') as string || '',
    country: formData.get('country') as string || 'US',

    // Shipping Address
    shippingAddress1: formData.get('shippingAddress1') as string || '',
    shippingAddress2: formData.get('shippingAddress2') as string || '',
    shippingCity: formData.get('shippingCity') as string || '',
    shippingState: formData.get('shippingState') as string || '',
    shippingZip: formData.get('shippingZip') as string || '',
    shippingCountry: formData.get('shippingCountry') as string || 'US',
    useSeparateShipping: formData.get('useSeparateShipping') === 'true',

    // Contact
    phone: formData.get('phone') as string || '',
    email: formData.get('email') as string || '',
    website: formData.get('website') as string || '',

    // Tax
    taxId: formData.get('taxId') as string || '',
    taxExempt: formData.get('taxExempt') === 'true',
    taxExemptNumber: formData.get('taxExemptNumber') as string || '',

    // Credit
    creditStatus: formData.get('creditStatus') as string || 'pending',
    creditLimit: formData.get('creditLimit') as string || '0',
    openBalance: formData.get('openBalance') as string || '0',
    creditTerms: formData.get('creditTerms') as string || 'Net 30',

    // Settings
    preferredLocationId: formData.get('preferredLocationId') as string || '',
    defaultPaymentMethod: formData.get('defaultPaymentMethod') as string || '',
    status: formData.get('status') as string || 'active',
    internalNotes: formData.get('internalNotes') as string || '',
  };

  // Validate form data
  const formValidation = customerFormSchema.safeParse(rawData);
  if (!formValidation.success) {
    return {
      success: false,
      error: 'Validation failed',
      errors: formValidation.error.flatten().fieldErrors as Record<string, string[]>,
    };
  }

  const result = await customerService.createFromForm(formValidation.data, appUser.id);

  if (result.success) {
    revalidatePath('/customers');
    revalidatePath('/api/customers');
  }

  return result;
}

